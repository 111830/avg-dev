let a = 3, b = 2;

let z = a + b;
console.log("The sum is: " + z);

z = a - b;
console.log("The difference is: " + z);

z = a * b;
console.log("The product is: " + z);

z = a / b;
console.log("The quotient is: " + z);

z = a % b;
console.log("The remainder is: " + z);

z = a ** b;
console.log("The power is: " + z);

// Now z is 9, and we are going to move on to other operators like ++ or -- 

z = ++a;
console.log(a);
console.log(z);

z = ++b;
console.log(b);
console.log(z);

z = a++;
console.log(a);
console.log(z);

z = b++;
console.log(b);
console.log(z);